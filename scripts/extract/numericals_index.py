"""Writes docs/numericals-index.md from data/numericals.json: every subject, formula family, and the book page / question number
of numericals whose worked solution could not be recovered cleanly.   python3 -I scripts/extract/numericals_index.py"""
import json, collections
from pathlib import Path
root = Path(__file__).resolve().parents[2]
num = json.loads((root / "data/numericals.json").read_text("utf8"))
BOOK = {"CIV1": "Civil Vol-1", "CIV2": "Civil Vol-2", "PYQ": "AE PYQ book", "THR": "Mechanical/Chemical book", "MAT": "Mechanical/Chemical book"}
page, text = {}, {}
for f in ["civil-vol1", "civil-vol2", "gs-civil-pyq", "civil-vol1-unverified", "civil-vol2-unverified", "gs-civil-pyq-unverified", "mech-thermo", "mech-materials", "chem-process", "chem-materials"]:
    for q in json.loads((root / "data/questions" / f"{f}.json").read_text("utf8")):
        if q["id"] in num:
            page[q["id"]] = q.get("sourcePage")
fam = collections.defaultdict(list)
for i, v in num.items():
    fam[(v["subjectName"], v["family"], v["formula"])].append(i)
subs = collections.defaultdict(list)
for k, ids in fam.items():
    subs[k[0]].append((len(ids), k, ids))
lines = ["# Technical Subjects Numericals — index", "",
         "Generated by `scripts/extract/numericals_index.py` from `data/numericals.json`. In the app: **Tests → Technical Subjects Numericals**; each topic is one formula family.",
         "Questions listed as *not recovered cleanly* have no reliable worked solution in the extracted text — look them up in the book by the reference given.", ""]
total = sum(len(v) for v in fam.values())
lines.append(f"**{total}** numericals · **{sum(1 for v in num.values() if v['solved'])}** with a worked solution · **{sum(1 for v in num.values() if not v['solved'])}** need the book.\n")
for sub in sorted(subs, key=lambda s: -sum(n for n, _, _ in subs[s])):
    lines += [f"## {sub} ({sum(n for n, _, _ in subs[sub])})", ""]
    for n, (s, f, formula), ids in sorted(subs[sub], reverse=True):
        un = [i for i in ids if not num[i]["solved"]]
        lines.append(f"### {f} — {n}")
        lines.append(f"Key formula: `{formula}`  ")
        lines.append(f"Worked solutions: {n - len(un)} · to look up in the book: {len(un)}")
        if un:
            refs = ", ".join(f"{BOOK.get(i.split('-')[0], i.split('-')[0])} p.{page.get(i)}" + (f" Q.{num[i]['qno']}" if num[i]["qno"] else "") for i in sorted(un))
            lines.append(f"> Book references: {refs}")
        lines.append("")
(root / "docs/numericals-index.md").write_text("\n".join(lines), "utf8")
print(total, "->", len(lines), "lines")
